export function getLocale(): Locale {
  return current;
}

export function getIntlLocale() {
  return current === "me" ? "sr-Latn-ME" : current === "en" ? "en-GB" : "ru-RU";
}

export function setLocale(locale: Locale) {
  current = locale;
  if (typeof localStorage !== "undefined") localStorage.setItem("red.locale", locale);
  if (typeof window !== "undefined") window.location.reload();
}

export function translateText(value: string) {
  if (current === "ru" || !value.trim()) return value;
  const leading = value.match(/^\s*/)?.[0] ?? "";
  const trailing = value.match(/\s*$/)?.[0] ?? "";
  let result = value.trim().replace(/\s+/g, " ");
  for (const [ru, me, en] of [...rules].sort((a, b) => b[0].length - a[0].length)) {
    result = result.replaceAll(ru, current === "me" ? me : en);
  }
  return leading + result + trailing;
}

function translateNode(node: Node) {
  if (node.nodeType === Node.TEXT_NODE && node.nodeValue) {
    const translated = translateText(node.nodeValue);
    if (translated !== node.nodeValue) node.nodeValue = translated;
    return;
  }
  if (!(node instanceof Element)) return;
  for (const name of ["aria-label", "placeholder", "title"]) {
    const value = node.getAttribute(name);
    if (value) {
      const translated = translateText(value);
      if (translated !== value) node.setAttribute(name, translated);
    }
  }
  node.childNodes.forEach(translateNode);
}

export function installTranslator() {
  if (typeof document === "undefined") return;
  document.documentElement.lang = current === "me" ? "sr-Latn-ME" : current;
  document.title = current === "me" ? "Red — elektronski red" : current === "en" ? "Red — electronic queue" : "Red — электронная очередь";
  const nativeConfirm = window.confirm.bind(window);
  const nativePrompt = window.prompt.bind(window);
  window.confirm = (message?: string) => nativeConfirm(translateText(String(message ?? "")));
  window.prompt = (message?: string, defaultValue?: string) =>
    nativePrompt(translateText(String(message ?? "")), defaultValue);
  translateNode(document.body);
  const observer = new MutationObserver((changes) => {
    for (const change of changes) {
      change.addedNodes.forEach(translateNode);
      if (change.type === "characterData") translateNode(change.target);
      if (change.type === "attributes") translateNode(change.target);
    }
  });
  observer.observe(document.body, {
    childList: true,
    subtree: true,
    characterData: true,
    attributes: true,
    attributeFilter: ["aria-label", "placeholder", "title"],
  });
}
